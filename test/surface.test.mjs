import assert from "node:assert/strict"
import fs from "node:fs"
import { test } from "bun:test"

test("页面、设置面板和 hook 接到插件清单，页面脚本都在外部文件", () => {
  const pkg = JSON.parse(fs.readFileSync(new URL("../package.json", import.meta.url), "utf8"))
  assert.equal(pkg.name, "@magpie-community/page-translator")
  assert.equal(pkg.type, "module")
  assert.equal(pkg.license, "MIT")
  assert.equal(pkg.main, undefined)
  assert.equal(pkg.exports, undefined)
  assert.equal(pkg.bin, undefined)
  assert.equal(pkg.scripts, undefined)
  assert.equal(pkg.engines, undefined)
  assert.equal(pkg.magpie.hooks, "./src/hooks.mjs")
  assert.equal(pkg.magpie.middleware, "./src/middleware.mjs")
  assert.equal(pkg.magpie.page.file, "page/index.html")
  assert.equal(pkg.magpie.page.titles.zh, "翻译记录")
  assert.equal(pkg.magpie.page.icon, "page/icon.svg")
  assert.equal(pkg.magpie.panels[0].slot, "settings")
  assert.equal(pkg.magpie.panels[0].file, "page/settings.html")
  assert.equal(pkg.magpie.panels[0].titles.zh, "翻译设置")
  assert.equal(pkg.magpie.icon, undefined)
  assert.deepEqual(pkg.magpie.permissions, ["providers:list", "usage:summary"])
  assert.equal(pkg.magpie.options.localPanel, undefined)
  assert.equal(pkg.magpie.options.panelPort, undefined)
  assert.equal(pkg.magpie.options.gatewayTimeoutMs, 10000)
  const icon = fs.readFileSync(new URL("../page/icon.svg", import.meta.url), "utf8")
  assert.match(icon, /viewBox="0 0 64 64"/)
  assert.match(icon, /#5b5bd6/)
  assert.equal(icon.includes("<text"), false)
  const app = fs.readFileSync(new URL("../page/app.js", import.meta.url), "utf8")
  assert.match(app, /providers:list/)
  assert.match(app, /usage:summary/)
  assert.equal(app.includes("fetch("), false)
  assert.equal(app.includes("feed.js"), false)
  assert.match(app, /_compare/)
  for (const file of ["page/settings.html", "page/index.html"]) {
    const html = fs.readFileSync(new URL(`../${file}`, import.meta.url), "utf8")
    assert.equal(/<script(?![^>]*\bsrc=)/.test(html), false, file)
    assert.equal(html.includes("onclick="), false, file)
    assert.equal(html.includes("<form"), false, file)
    assert.match(html, /_magpie\/bridge\.js/)
    assert.match(html, /style\.css/)
    assert.match(html, /app\.js/)
  }
  const middleware = fs.readFileSync(new URL("../src/middleware.mjs", import.meta.url), "utf8")
  assert.equal(middleware.includes("from "), false)
  assert.equal(/^(?:let|var|const) /m.test(middleware), false)
  assert.equal(fs.existsSync(new URL("../src/panel.mjs", import.meta.url)), false)
  assert.equal(fs.existsSync(new URL("../src/worker.mjs", import.meta.url)), false)
})
